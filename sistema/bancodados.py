class _CursorPG:
    """Cursor com a interface que o sistema usa (fetch*, iteração, lastrowid)."""

    def __init__(self, cursor, lastrowid=None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def __iter__(self):
        return iter(self._cursor.fetchall())


class ConexaoPostgres:
    """Conexão PostgreSQL com a interface do sqlite3 usada pelo sistema."""

    def __init__(self, url: str):
        import psycopg2  # import tardio: só é preciso em produção

        self._psycopg2 = psycopg2
        self._conexao = psycopg2.connect(url)

    def execute(self, sql: str, parametros=()):  # noqa: A003
        cursor = self._conexao.cursor()
        traduzido = com_returning(traduzir_sql(sql))
        try:
            cursor.execute(traduzido, tuple(parametros))
        except self._psycopg2.IntegrityError as erro:
            raise sqlite3.IntegrityError(str(erro).strip()) from erro
        lastrowid = None
        if traduzido.rstrip().upper().endswith("RETURNING ID"):
            linha = cursor.fetchone()
            lastrowid = linha[0] if linha else None
        return _CursorPG(cursor, lastrowid)

    def executemany(self, sql: str, seq_parametros):
        cursor = self._conexao.cursor()
        try:
            cursor.executemany(traduzir_sql(sql),
                               [tuple(p) for p in seq_parametros])
        except self._psycopg2.IntegrityError as erro:
            raise sqlite3.IntegrityError(str(erro).strip()) from erro
        return _CursorPG(cursor)

    def executescript(self, script: str):
        # Texto puro (schema/seed): sem parâmetros, sem tradução de `%`.
        cursor = self._conexao.cursor()
        cursor.execute(script)
        return _CursorPG(cursor)

    def commit(self):
        self._conexao.commit()

    def rollback(self):
        self._conexao.rollback()

    def close(self):
        self._conexao.close()
