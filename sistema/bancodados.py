"""Adaptador de banco: SQLite (local/testes) e PostgreSQL/Supabase (produção).

Todo o sistema fala o dialeto do sqlite3 (placeholders `?`, `lastrowid`,
`executescript`). Este módulo permite apontar a MESMA base de código para
um PostgreSQL (ex.: Supabase) via `DATABASE_URL`, traduzindo em tempo de
execução:

- `?`  → `%s` (fora de aspas) e `%` literal → `%%`;
- INSERTs ganham `RETURNING id` para alimentar `lastrowid` (exceto tabelas
  sem coluna id);
- `executescript` roda o texto puro (schema/seed, sem tradução);
- erros de integridade do psycopg2 são re-erguidos como
  `sqlite3.IntegrityError`, que é o que a API trata.

O schema é convertido trocando `INTEGER PRIMARY KEY` (autoincremento do
SQLite) por coluna IDENTITY do PostgreSQL; após o seed (que fixa ids
explícitos), as sequências são realinhadas com `setval`.
"""

from __future__ import annotations

import re
import sqlite3

# Tabelas sem coluna `id` (chave composta) — não recebem RETURNING id.
_TABELAS_SEM_ID = {"unidade_area", "unidade_acao", "simbolo", "rubrica"}

_INSERT_RE = re.compile(r"^\s*INSERT\s+INTO\s+([\"a-zA-Z_][\"\w]*)",
                        re.IGNORECASE)


def eh_url_postgres(caminho: str) -> bool:
    return str(caminho).startswith(("postgres://", "postgresql://"))


def traduzir_sql(sql: str) -> str:
    """Traduz uma consulta do dialeto sqlite3 para psycopg2.

    Troca `?` por `%s` fora de literais de texto e escapa `%` (o psycopg2
    interpreta `%` quando há parâmetros).
    """
    saida = []
    em_aspas = False
    for ch in sql:
        if ch == "'":
            em_aspas = not em_aspas
            saida.append(ch)
        elif ch == "?" and not em_aspas:
            saida.append("%s")
        elif ch == "%":
            saida.append("%%")
        else:
            saida.append(ch)
    return "".join(saida)


def com_returning(sql: str) -> str:
    """Anexa RETURNING id aos INSERTs de tabelas com id (para lastrowid)."""
    m = _INSERT_RE.match(sql)
    if not m:
        return sql
    tabela = m.group(1).strip('"').lower()
    if tabela in _TABELAS_SEM_ID or "returning" in sql.lower():
        return sql
    return sql.rstrip().rstrip(";") + " RETURNING id"


def schema_para_postgres(schema_sql: str) -> str:
    """Converte o schema portável para PostgreSQL (autoincremento)."""
    return schema_sql.replace(
        "INTEGER PRIMARY KEY",
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")


